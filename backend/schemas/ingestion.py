from datetime import datetime
from uuid import UUID
from pydantic import BaseModel, Field, ConfigDict
from typing import Dict, Any, Optional

class IngestionRequest(BaseModel):
    agent_id: UUID = Field(..., description="ID of the agent receiving this content")
    content: str = Field(..., min_length=1, max_length=100000, description="Normalized untrusted content")
    source_type: str = Field(..., min_length=1, max_length=50, description="Type of source (e.g., email, web, document)")
    provenance: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Metadata about the source origin")

class IngestionResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    
    id: UUID
    agent_id: UUID
    source_type: str
    provenance: Optional[Dict[str, Any]]
    created_at: datetime
    status: str = Field(default="processed", description="Status of the ingestion analysis")
    decision: str = Field(default="ALLOW", description="ALLOW, BLOCK, or QUARANTINE")
    risk_score: int = Field(default=0, description="Risk score generated by the semantic firewall")
    reason: str = Field(default="Safe content", description="Reason for the firewall decision")
    metadata: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Detailed detection metadata")

