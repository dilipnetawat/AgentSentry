from pydantic import BaseModel, Field
from typing import Dict, Any, Optional

class DetectionResult(BaseModel):
    detected: bool = Field(default=False, description="True if any suspicious/malicious patterns were found")
    risk_score: int = Field(..., ge=0, le=100, description="Risk score generated by the detector")
    category: str = Field(default="safe", description="Primary attack category detected")
    reason: str = Field(..., description="Explanation for the risk score")
    matched_indicators: list[str] = Field(default_factory=list, description="Specific strings/patterns matched")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Additional detection metadata")

class FirewallDecision(BaseModel):
    decision: str = Field(..., description="ALLOW, BLOCK, or QUARANTINE")
    risk_score: int = Field(..., description="Highest risk score across all detectors")
    reason: str = Field(..., description="Explanation for the decision")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Combined metadata from detectors")
